import { readFile, writeFile, mkdtemp, copyFile, rm } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const source = await readFile(new URL("public/mw-logo.svg", root), "utf8");
const viewBox = source
  .match(/viewBox="([^"]+)"/)?.[1]
  .split(/\s+/)
  .map(Number);
if (
  !viewBox ||
  viewBox.length !== 4 ||
  !viewBox.every(Number.isFinite) ||
  viewBox[2] <= 0 ||
  viewBox[3] <= 0
) {
  throw new Error("mw-logo.svg must have a valid viewBox.");
}

// Fit the source into a 24px box, centred in a transparent 32px favicon.
const scale = 24 / Math.max(viewBox[2], viewBox[3]);
const width = viewBox[2] * scale;
const height = viewBox[3] * scale;
const artwork = source.replace(
  /<svg\b[^>]*>/,
  `<svg x="${(32 - width) / 2}" y="${(32 - height) / 2}" width="${width}" height="${height}" viewBox="${viewBox.join(" ")}">`,
);
const icon = `<!-- Generated by pnpm generate:logo; edit public/mw-logo.svg. -->\n<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 32 32">\n${artwork.trim()}\n</svg>\n`;
const temporary = await mkdtemp(join(tmpdir(), "site-favicons-"));
try {
  const svgPath = join(temporary, "icon.svg");
  const icoPath = join(temporary, "favicon.ico");
  await writeFile(svgPath, icon);
  try {
    execFileSync(
      "magick",
      [
        "-background",
        "none",
        svgPath,
        "-filter",
        "point",
        "-define",
        "icon:auto-resize=32,16",
        icoPath,
      ],
      { stdio: "pipe" },
    );
  } catch (error) {
    throw new Error(
      "Favicon generation requires ImageMagick 7 (magick). Existing assets were not changed.",
      { cause: error },
    );
  }
  await copyFile(svgPath, fileURLToPath(new URL("app/icon.svg", root)));
  await copyFile(icoPath, fileURLToPath(new URL("app/favicon.ico", root)));
  console.log(
    "Generated transparent SVG and ICO favicons from public/mw-logo.svg.",
  );
} finally {
  await rm(temporary, { recursive: true, force: true });
}
